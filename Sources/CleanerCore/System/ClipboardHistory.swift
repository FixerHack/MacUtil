import AppKit
import Foundation

/// Something that was on the clipboard.
public struct ClipboardEntry: Codable, Sendable, Identifiable, Hashable {
    public enum Kind: String, Codable, Sendable {
        case text, url, file
    }

    public let id: UUID
    public let text: String
    public let kind: Kind
    public let copiedAt: Date
    /// The app it was copied from, when macOS says.
    public let source: String?

    public init(text: String, kind: Kind, source: String?, copiedAt: Date = Date(), id: UUID = UUID()) {
        self.id = id
        self.text = text
        self.kind = kind
        self.source = source
        self.copiedAt = copiedAt
    }

    /// One line, for a list that must not grow tall.
    public var preview: String {
        let flat = text
            .replacingOccurrences(of: "\n", with: " ")
            .replacingOccurrences(of: "\t", with: " ")
            .trimmingCharacters(in: .whitespacesAndNewlines)
        return flat.count > 200 ? String(flat.prefix(200)) + "…" : flat
    }
}

/// Remembers what has been copied, so the thing copied three things ago is not lost.
///
/// A clipboard watcher sees everything typed into a password field and copied, so what it
/// must *not* remember matters more than what it does. Password managers mark their items
/// concealed, and those are skipped; so is anything marked transient or auto-generated.
/// The history is off until it is switched on, kept to a fixed number of entries, and can
/// be emptied in one press.
public enum ClipboardHistory {
    public static let enabledKey = "clipboardHistory"
    public static let limitKey = "clipboardHistoryLimit"
    public static let defaultLimit = 100

    /// Hints other apps put on the pasteboard to say "do not keep this".
    static let concealed: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        // 1Password's own marker, which predates the convention above.
        .init("com.agilebits.onepassword"),
    ]

    public static var isEnabled: Bool {
        UserDefaults.standard.bool(forKey: enabledKey)
    }

    public static var limit: Int {
        let stored = UserDefaults.standard.integer(forKey: limitKey)
        return stored > 0 ? stored : defaultLimit
    }

    public static var url: URL {
        AppPaths.file("Clipboard.json")
    }

    // MARK: - Reading the pasteboard

    /// True when the pasteboard says this item is not to be remembered.
    public static func isConcealed(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        types.contains { concealed.contains($0) }
    }

    /// What is on the pasteboard now, or nil when there is nothing worth keeping.
    public static func current(_ pasteboard: NSPasteboard = .general, source: String? = nil) -> ClipboardEntry? {
        let types = pasteboard.types ?? []
        guard !isConcealed(types) else { return nil }

        if let files = pasteboard.propertyList(forType: .fileURL) as? [String], !files.isEmpty {
            return ClipboardEntry(text: files.joined(separator: "\n"), kind: .file, source: source)
        }
        if let url = pasteboard.string(forType: .URL), !url.isEmpty {
            return ClipboardEntry(text: url, kind: .url, source: source)
        }
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return nil }
        // A web address copied as plain text is still a web address.
        let kind: ClipboardEntry.Kind = text.hasPrefix("http://") || text.hasPrefix("https://") ? .url : .text
        return ClipboardEntry(text: text, kind: kind, source: source)
    }

    // MARK: - The list

    /// Puts an entry at the top, moving it there if it was already in the list.
    public static func adding(_ entry: ClipboardEntry, to entries: [ClipboardEntry], limit: Int = limit)
        -> [ClipboardEntry]
    {
        var updated = entries.filter { $0.text != entry.text }
        updated.insert(entry, at: 0)
        return Array(updated.prefix(max(1, limit)))
    }

    public static func load(from url: URL = url) -> [ClipboardEntry] {
        guard let data = try? Data(contentsOf: url),
              let entries = try? JSONDecoder().decode([ClipboardEntry].self, from: data)
        else { return [] }
        return entries
    }

    public static func save(_ entries: [ClipboardEntry], to url: URL = url) {
        try? FileManager.default.createDirectory(
            at: url.deletingLastPathComponent(), withIntermediateDirectories: true
        )
        guard let data = try? JSONEncoder().encode(entries) else { return }
        try? data.write(to: url, options: [.atomic, .completeFileProtection])
    }

    public static func forget(at url: URL = url) {
        try? FileManager.default.removeItem(at: url)
    }

    /// Puts an entry back on the clipboard.
    public static func copy(_ entry: ClipboardEntry, to pasteboard: NSPasteboard = .general) {
        pasteboard.clearContents()
        pasteboard.setString(entry.text, forType: .string)
    }
}
